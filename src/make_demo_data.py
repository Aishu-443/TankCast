"""Generate SYNTHETIC DEMO DATA for testing the pipeline and (later) the dashboard.

    python -m src.make_demo_data

Everything here is random numbers shaped like a hostel's daily water-use rhythm. It is NOT real
data. Any model trained on it shows only that the code runs; its metrics say nothing about the real world.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from src.data_loader import PROJECT_ROOT

DEMO_PATH = PROJECT_ROOT / "data" / "demo" / "synthetic_hostel_hourly_DEMO.csv"


def generate_demo_frame(days: int = 120, seed: int = 42) -> pd.DataFrame:
    """Hourly litres/hour with morning/midday/evening peaks, quieter weekends, noise and a few gaps."""
    rng = np.random.default_rng(seed)
    ts = pd.date_range("2025-01-01", periods=days * 24, freq=pd.Timedelta(hours=1))
    hour = ts.hour.to_numpy()
    peaks = (520 * np.exp(-0.5 * ((hour - 7) / 1.5) ** 2) + 150 * np.exp(-0.5 * ((hour - 13) / 1.5) ** 2)
             + 380 * np.exp(-0.5 * ((hour - 20) / 2.0) ** 2))
    weekend = np.where(ts.dayofweek >= 5, 0.85, 1.0)
    demand = (80 + peaks) * weekend * rng.normal(1.0, 0.08, len(ts))
    frame = pd.DataFrame({"timestamp": ts, "demand_litres_per_hour": demand.round(1).clip(min=0)})
    return frame.drop(index=rng.choice(len(frame), size=6, replace=False)).reset_index(drop=True)  # a few gaps


def write_demo(path: Path = DEMO_PATH) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    generate_demo_frame().to_csv(path, index=False)
    meta = {
        "data_status": "SYNTHETIC DEMO DATA",
        "is_synthetic": True,
        "source": "generated by src/make_demo_data.py (random numbers, seed 42)",
        "unit": "litres per hour",
        "date_column": "timestamp",
        "target_column": "demand_litres_per_hour",
        "limitations": ["Not real measurements. Metrics from this file must never be presented as real-world results."],
    }
    path.with_suffix(".meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    return path


if __name__ == "__main__":
    print(f"Wrote SYNTHETIC DEMO DATA to {write_demo()}")
    sys.exit(0)
